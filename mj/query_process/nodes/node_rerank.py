from mj.query_process.base import NodeBase
from mj.query_process.state import QueryGraphState
from mj.tool.logger import logger
from tool.json_format_tool import json_format
from tool.rerank_tool import text_rerank


class NodeRerank(NodeBase):
    """
    节点功能：使用 Cross-Encoder 模型对 RRF 后的结果进行精确打分重排。
    """

    # 覆盖基类的 name 属性，标识节点名称
    name: str = "node_rerank"

    def process(self, state: QueryGraphState):
        rrf_chunks = state.get("rrf_chunks")
        web_search_docs = state.get("web_search_docs")
        rewritten_query = state.get("rewritten_query")

        # 合并数据
        merged_chunks = rrf_chunks + web_search_docs
        merged_chunks = [
            {
                "content": item.get("content") or item.get("section_content"),
                "title": item.get("item_name") or item.get("title"),
                "url": item.get("url", ""),
                "source": item.get("source")
            }
            for item in merged_chunks
        ]

        # 将合并后的数据使用rerank模型评分
        merged_chunks_str = [item.get("content") for item in merged_chunks]

        logger.info("merged_chunks_str============================================")
        logger.info(merged_chunks_str)
        logger.info("rrf_chunks============================================")
        logger.info(rrf_chunks)
        logger.info("web_search_docs============================================")
        logger.info(web_search_docs)
        logger.info("============================================")
        logger.info("============================================")
        logger.info("============================================")
        logger.info("============================================")

        res = text_rerank(query=rewritten_query, documents=merged_chunks_str)

        for item in res:
            merged_chunks[item.get("index")]["score"] = item.get("score")

        rerank_chunks = sorted(merged_chunks, key=lambda x: x["score"], reverse=True)

        # 后面做断崖检测
        # 断崖检测算法就是为了让我们能够拿到所有的分数高的chunks,因此这里必须是动态topk，不能写死
        # 动态 TopK：硬上限：最多取前 N 条（<=10）
        RERANK_MAX_TOPK: int = 18
        # 最小 TopK：至少保留前 N 条（>=1，且 <= RERANK_MAX_TOPK）
        # RERANK_MIN_TOPK: int = 3  # 总数最少条数
        # 断崖阈值（相对）
        RERANK_GAP_RATIO: float = 0.25
        # 断崖阈值（绝对）
        RERANK_GAP_ABS: float = 0.1

        # 计算我们的实际上限和下限
        use_max_topk = min(RERANK_MAX_TOPK, len(rerank_chunks))
        # use_min_topk=min(RERANK_MIN_TOPK,len(rerank_chunks))

        break_idx = use_max_topk

        for i in range(0, len(rerank_chunks)-1):
            current_score = rerank_chunks[i].get("score")
            next_score = rerank_chunks[i + 1].get("score")

            gap_abs = current_score - next_score
            gap_ratio = gap_abs / (current_score + 1e-6)

            if gap_abs > RERANK_GAP_ABS or gap_ratio > RERANK_GAP_RATIO:
                break_idx = i + 1
                break

        print(json_format(rerank_chunks[:break_idx]))

        return {
            "reranked_docs": rerank_chunks[:break_idx],
        }



